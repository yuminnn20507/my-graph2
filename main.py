import plotly.graph_objects as go


# ============================================================
# 페이지 설정
# ============================================================

st.set_page_config(
    page_title="영화 데이터 그래프 도감 2 - 분포와 관계",
    page_icon="🎬",
    layout="wide"
)


# ============================================================
# 제목
# ============================================================

st.title("🎬 영화 데이터 그래프 도감 2 - 분포와 관계")

st.write(
    "영화 데이터를 장르, 국가, 관객 수 등의 기준으로 살펴보며 "
    "영화들의 분포와 관계를 확인합니다."
)


# ============================================================
# 데이터 불러오기
# ============================================================

DATA_URL = (
    "https://raw.githubusercontent.com/greatsong/modudata/"
    "main/data/kobis_movies.csv"
)


@st.cache_data
def load_data():

    df = pd.read_csv(
        DATA_URL,
        encoding="utf-8-sig"
    )

    # --------------------------------------------------------
    # 날짜 변환
    # --------------------------------------------------------

    df["openDt"] = pd.to_datetime(
        df["openDt"].astype(str),
        format="%Y%m%d",
        errors="coerce"
    )

    # --------------------------------------------------------
    # 숫자 열 변환
    # --------------------------------------------------------

    numeric_columns = [
        "movieCd",
        "first_scrn",
        "first_show",
        "first_week_audi",
        "total_audi",
        "days_in_top10"
    ]

    for column in numeric_columns:

        df[column] = pd.to_numeric(
            df[column],
            errors="coerce"
        )

    # --------------------------------------------------------
    # 장르 처리
    #
    # 예:
    # "드라마|멜로/로맨스|..."
    # → "드라마"
    # --------------------------------------------------------

    df["genre"] = (
        df["genre"]
        .fillna("미상")
        .astype(str)
        .str.split("|")
        .str[0]
        .str.strip()
    )

    # 빈 장르는 미상으로 처리
    df.loc[
        df["genre"].isin(["", "nan", "None"]),
        "genre"
    ] = "미상"

    # 영화명이 없는 행 제거
    df = df.dropna(
        subset=["movieNm"]
    )

    return df


df = load_data()


# ============================================================
# 데이터 기본 정보
# ============================================================

st.caption(
    f"📊 총 {len(df):,}편의 영화 데이터를 불러왔습니다."
)


# ============================================================
# 그래프 1. 장르별 영화 편수
# ============================================================

st.divider()

st.header("📊 그래프 1. 장르별 영화 편수")

st.write(
    "이 기간에 개봉한 영화가 어떤 장르로 구성되어 있는지 살펴봅니다."
)


# ------------------------------------------------------------
# 장르별 영화 편수
# ------------------------------------------------------------

genre_counts = (
    df["genre"]
    .value_counts()
    .sort_values(ascending=False)
)


# ------------------------------------------------------------
# 도넛 그래프
# ------------------------------------------------------------

fig1 = go.Figure()

fig1.add_trace(
    go.Pie(
        labels=genre_counts.index,
        values=genre_counts.values,

        # 도넛 모양
        hole=0.55,

        # 마우스를 올렸을 때 표시할 정보
        hovertemplate=(
            "<b>%{label}</b>"
            "<br>영화 편수: %{value}편"
            "<br>비율: %{percent}"
            "<extra></extra>"
        ),

        textinfo="label",

        # 조각을 너무 많이 표시하지 않도록
        # 범례에서 전체 장르를 확인할 수 있게 함
        sort=False
    )
)


fig1.update_layout(
    title="장르별 영화 편수",

    height=600,

    margin=dict(
        l=40,
        r=40,
        t=80,
        b=40
    ),

    legend=dict(
        title="장르"
    )
)


st.plotly_chart(
    fig1,
    use_container_width=True
)


# ============================================================
# 그래프 1 - 이 그래프로 알 수 있는 것
# ============================================================

st.markdown("### 💡 이 그래프로 알 수 있는 것")

st.write(
    "이 기간에 개봉한 영화들이 어떤 장르에 많이 분포되어 있는지 확인할 수 있습니다."
)


